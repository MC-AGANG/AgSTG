double GetAngle(double x1, double y1, double x2, double y2)
{
	double angle_temp;
	double xx, yy;
	xx = x2 - x1;
	yy = y2 - y1;
	if (xx == 0.0)
		angle_temp = pi / 2.0;
	else
		angle_temp = atan(fabs(yy / xx));
	if ((xx < 0.0) && (yy >= 0.0))
		angle_temp = pi - angle_temp;
	else if ((xx < 0.0) && (yy < 0.0))
		angle_temp = pi + angle_temp;
	else if ((xx >= 0.0) && (yy < 0.0))
		angle_temp = pi * 2.0 - angle_temp;
	return (angle_temp/pi*180+90);
}
